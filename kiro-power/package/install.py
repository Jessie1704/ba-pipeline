def mig_gate_wording(text):
    """Gate descriptions of the predecessors' templates -> the current wording (results and notes are kept)."""
    for old, new in OLD_GATE_TEXT.items():
        text = text.replace(old, new)
    return text


MIGRATIONS = [
    ("preferences-section", "add the Preferences section", mig_preferences),
    ("elicitation-round", "add the 'Elicitation round' preference", mig_elicitation_round),
    ("revisit-at", "add the 'Revisit at' column to the Decision log", mig_revisit_at),
    ("answer-mode", "add the 'Answer mode' preference", mig_answer_mode),
    ("questions-per-message", "add the 'Questions per message' preference (walkthrough)", mig_questions_per_message),
    ("governance", "add the Governance section (business owner, PO, area owners, escalation)", mig_governance),
    ("mode", "add the 'Mode' preference (quick · standard · controlled)", mig_mode),
    ("language", "add the 'Language' preference (en · vi)", mig_language),
    ("delivery-gates", "add the delivery gates (10 Refine, 11 Test/UAT, 12 Release)", mig_delivery_gates),
    ("gate-wording", "update gate descriptions (human gates 👤, review verdict by defects)", mig_gate_wording),
]


def migrate_features(target, requirements_dir, dry_run):
    """Apply status-template migrations; returns {feature: [migration ids]}."""
    done = {}
    folder = target / requirements_dir
    if not folder.is_dir():
        return done
    for feature in sorted(p for p in folder.iterdir() if (p / "_status.md").is_file()):
        status = feature / "_status.md"
        original = text = status.read_text(encoding="utf-8")
        applied = []
        for mig_id, _, apply in MIGRATIONS:
            new = apply(text)
            if new != text:
                applied.append(mig_id)
                text = new
        if not re.search(r"^## Approach", text, re.M):
            say("attention", f"{feature.name}: _status.md has no Approach section - run /ba-intake step 5 (not automatic)")
        if applied:
            stamp = datetime.date.today().isoformat()
            note = f"- {stamp} — Migrated to BA Pipeline {VERSION} status template: {', '.join(applied)}."
            text = text.rstrip("\n") + ("\n" + note + "\n" if re.search(r"^## History", text, re.M) else f"\n\n## History\n{note}\n")
            say("migrate", f"{feature.name}: {', '.join(applied)}")
            if "governance" in applied:
                say("attention", f"{feature.name}: fill _status.md -> Governance: business owner, and every area "
                                 f"(module, process, integration) with its owner - nobody can flag an area not listed")
                intake = next(iter(sorted(feature.glob("01-*.md"))), None)
                if intake and not list(feature.glob("03-*.md")) and "## Foundations" not in intake.read_text(encoding="utf-8-sig"):
                    say("attention", f"{feature.name}: scope not written yet - run the foundation check first (ba-intake "
                                     f"step 4b): missing success metrics or owners become Decision-critical questions")
            done[feature.name] = applied
            if not dry_run and text != original:
                adapters.write_lf(status, text)
    return done


# --------------------------------------------------------------------------- audit (through the installed ba.py)

def ba_cli(target, *args):
    tool = target / ".ba" / "tools" / "ba.py"
    if not tool.is_file():
        return
    result = subprocess.run([sys.executable, str(tool), "--root", str(target), *args], capture_output=True, text=True,
                            encoding="utf-8", errors="replace")
    if result.returncode != 0:
        say("warning", f"ba {' '.join(args[:3])}: {result.stderr.strip() or result.stdout.strip()}")


def record(target, event_type, summary, feature=None):
    args = ["audit", "event", "--type", event_type, "--summary", summary, "--actor", "ba-pipeline installer"]
    if feature:
        args[2:2] = ["--feature", feature]
    ba_cli(target, *args)


# --------------------------------------------------------------------------- legacy layout

def legacy_parts(target):
    """Paths belonging to the original Claude-only layout (before packaging)."""
    parts = []
    claude_md = target / "CLAUDE.md"
    claude_text = claude_md.read_text(encoding="utf-8") if claude_md.is_file() else ""
    if "BA Copilot" in claude_text and not adapters.BLOCK_RX.search(claude_text):  # the pre-package BA Copilot layout
        parts.append(claude_md)
    skills = target / ".claude" / "skills"
    if skills.is_dir():
        for skill in sorted(skills.glob("ba-*/SKILL.md")):
            if not adapters.MARK_RX.search(skill.read_text(encoding="utf-8")):
                parts.append(skill.parent)
    agent = target / ".claude" / "agents" / "requirements-reviewer.md"
    if agent.is_file() and not adapters.MARK_RX.search(agent.read_text(encoding="utf-8")):
        parts.append(agent)
    hooks = target / ".claude" / "hooks"
    legacy_scripts = {"audit-event.ps1", "audit-lib.ps1", "audit-log.ps1", "audit-verify.ps1", "ba-check.ps1"}
    parts += sorted(p for p in hooks.glob("*.ps1") if p.name in legacy_scripts) if hooks.is_dir() else []
    if not parts:
        return parts  # root folders below only count as legacy next to the legacy Claude files
    # Root folders count only if they hold BA Pipeline's own marker files (a project may have unrelated ones).
    markers = {"templates": "_status.md", "checklists": "definition-of-ready.md", "profiles": "_template.md"}
    for name, marker in markers.items():
        if (target / name / marker).is_file():
            parts.append(target / name)
    glossary = target / "glossary.md"
    if glossary.is_file() and "Organisation Glossary" in glossary.read_text(encoding="utf-8"):
        parts.append(glossary)
    return parts


def migrate_legacy(target, dry_run):
    parts = legacy_parts(target)
    if not parts:
        say("legacy", "nothing to migrate")
        return
    backup = target / ".ba" / "backup" / f"legacy-{datetime.date.today().isoformat()}"
    local = target / ".ba" / "local"
    # Project-owned content first: glossary, and profiles/templates/checklists the core doesn't have.
    if target / "glossary.md" in parts:
        say("keep", "glossary.md -> .ba/local/glossary.md (project glossary)")
        if not dry_run:
            local.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target / "glossary.md", local / "glossary.md")
    for name in LOCAL_DIRS:
        folder = target / name
        if folder not in parts:
            continue
        for path in sorted(p for p in folder.rglob("*") if p.is_file()):
            rel = path.relative_to(folder)
            core_file = PACKAGE / "core" / name / rel
            if not core_file.is_file():
                say("keep", f"{name}/{rel.as_posix()} -> .ba/local/{name}/ (not in core)")
                if not dry_run:
                    (local / name / rel).parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(path, local / name / rel)
            elif core_file.read_bytes() != path.read_bytes():
                say("review", f"{name}/{rel.as_posix()} differs from core - backed up; copy to .ba/local/{name}/ if it holds your own changes")
    # Everything legacy moves into the backup (nothing is deleted).
    for path in parts:
        rel = path.relative_to(target)
        say("backup", f"{rel.as_posix()} -> {backup.relative_to(target).as_posix()}/{rel.as_posix()}")
        if not dry_run:
            dest = backup / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(path), str(dest))
    # Old PowerShell audit hook out of .claude/settings.json (the adapter adds the Python one).
    settings = target / ".claude" / "settings.json"
    if settings.is_file():
        data = json.loads(settings.read_text(encoding="utf-8-sig"))
        groups = data.get("hooks", {}).get("PostToolUse", [])
        kept = []
        for group in groups:
            hooks = [h for h in group.get("hooks", []) if "audit-log.ps1" not in h.get("command", "")]
            if hooks:
                kept.append(dict(group, hooks=hooks))
        if kept != groups:
            say("settings", "removed the PowerShell audit hook from .claude/settings.json")
            if not dry_run:
                data["hooks"]["PostToolUse"] = kept
                adapters.write_lf(settings, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    for empty in (target / ".claude" / "hooks", target / ".claude" / "skills", target / ".claude" / "agents"):
        if not dry_run and empty.is_dir() and not any(empty.iterdir()):
            empty.rmdir()


# --------------------------------------------------------------------------- commands

def generate_adapters(target, tools, dry_run):
    actions = adapters.generate(target, tools, dry_run)
    counts = {}
    for state, rel in actions:
        counts[state] = counts.get(state, 0) + 1
        if state.startswith("skipped"):
            say("skipped", f"{rel} (your file, not generated - remove it to let the adapter create it)")
    say("adapters", ", ".join(f"{n} {s}" for s, n in sorted(counts.items())) + f"  [{', '.join(tools)}]")


def cmd_init(target, args):
    existing = read_config(target)
    if existing and existing.get("ba_version"):
        print(f"{product(existing)} {existing.get('ba_version')} is already installed in {target} - use 'update'.")
        return 1
    # A project that used the Kiro Power without installing has .ba/config.json with only settings: keep them.
    legacy = legacy_parts(target)
    if legacy and not args.from_legacy:
        print("This project has the original BA Copilot layout (pre-package):")
        for path in legacy:
            print(f"  {path.relative_to(target).as_posix()}")
        print("Re-run with --from-legacy to move it into .ba/backup/ and install the packaged version.")
        return 1
    tools = parse_tools(args.tools) or DEFAULT_TOOLS
    print(f"Installing BA Pipeline {VERSION} into {target}" + (" (dry run)" if args.dry_run else ""))
    copy_package(target, args.dry_run)
    ensure_local(target, args.dry_run)
    if args.from_legacy:
        migrate_legacy(target, args.dry_run)
    config = dict(existing or {})
    config.pop("package", None)  # installed now: the project uses its own .ba/ copy, not the power's
    config.update({"product": PRODUCT, "ba_version": VERSION,
                   "requirements_dir": config.get("requirements_dir") or args.requirements_dir,
                   "tools": tools})
    if args.model:
        config["model"] = args.model
    say("write", f".ba/config.json {json.dumps(config)}")
    write_config(target, config, args.dry_run)
    generate_adapters(target, tools, args.dry_run)
    migrated = migrate_features(target, args.requirements_dir, args.dry_run)
    if not args.dry_run:
        record(target, "ba.installed", f"BA Pipeline {VERSION} installed; tools: {', '.join(tools)}"
               + ("; migrated from legacy layout (backup in .ba/backup/)" if args.from_legacy else ""))
        for feature, ids in migrated.items():
            ba_cli(target, "audit", "sync", feature)
            record(target, "template.migrated", f"_status.md migrated to {VERSION}: {', '.join(ids)}", feature)
    print("\nNext: start a NEW session in your AI tool so it loads the generated commands, agents and hooks.")
    return 0


def cmd_update(target, args):
    config = read_config(target)
    if not config:
        print(f"BA Pipeline is not installed in {target} - use 'init'.")
        return 1
    installed = config.get("ba_version", "0")
    old_product = product(config)
    # A predecessor (BA Copilot 0.x, BA Guardian Angel 1.x) always upgrades: its version numbers are not comparable.
    same_product = old_product == PRODUCT
    if same_product and vtuple(VERSION) < vtuple(installed) and not args.force:
        print(f"Refusing to downgrade: project is pinned to {installed}, this package is {VERSION} (use --force).")
        return 1
    # --tools on update ADDS tools: a project set up for Claude Code keeps it when Kiro is added (never drops one)
    tools = list(dict.fromkeys((config.get("tools") or DEFAULT_TOOLS) + (parse_tools(args.tools) or [])))
    print(f"Updating {old_product} {installed} -> {PRODUCT} {VERSION} in {target}" + (" (dry run)" if args.dry_run else ""))
    for heading, body in changelog_since(installed if same_product else "0"):
        print(f"\n{heading}\n{body}")
    print()
    copy_package(target, args.dry_run)
    ensure_local(target, args.dry_run)
    config.update({"product": PRODUCT, "ba_version": VERSION, "tools": tools})
    if args.model:
        config["model"] = args.model
    elif not config.get("model"):
        say("attention", "no AI model on record: pass --model <name> (or set BA_MODEL) so the audit log shows which "
                         "model drafted what")
    write_config(target, config, args.dry_run)
    generate_adapters(target, tools, args.dry_run)
    migrated = migrate_features(target, config.get("requirements_dir", "requirements"), args.dry_run)
    report_overrides(target, installed)
    if not args.dry_run:
        record(target, "ba.updated", f"{old_product} {installed} -> {PRODUCT} {VERSION}; tools: {', '.join(tools)}")
        for feature, ids in migrated.items():
            ba_cli(target, "audit", "sync", feature)
            record(target, "template.migrated", f"_status.md migrated to {VERSION}: {', '.join(ids)}", feature)
    print("\nNext: start a NEW session in your AI tool so it loads any changed commands, agents and hooks.")
    return 0


def cmd_status(target, args):
    config = read_config(target)
    if not config:
        legacy = legacy_parts(target)
        print("BA Pipeline: not installed" + (" (original pre-package layout found - init --from-legacy)" if legacy else ""))
        return 1
    installed = config.get("ba_version")
    print(f"{product(config)} {installed} installed · package {PRODUCT} {VERSION}" +
          (" · update available" if product(config) != PRODUCT or vtuple(VERSION) > vtuple(installed) else ""))
    print(f"requirements: {config.get('requirements_dir')} · tools: {', '.join(config.get('tools', []))}")
    local = target / ".ba" / "local"
    overrides = sorted(p.relative_to(local).as_posix() for p in local.rglob("*") if p.is_file() and p.name != "README.md") if local.is_dir() else []
    print(f"local overrides: {len(overrides)}" + (f" ({', '.join(overrides)})" if overrides else ""))
    pending = migrate_features(target, config.get("requirements_dir", "requirements"), dry_run=True)
    print(f"features needing template migration: {len(pending)}" + (" - run update" if pending else ""))
    actions = adapters.generate(target, config.get("tools", []), dry_run=True)
    stale = [rel for state, rel in actions if state in ("created", "updated")]
    print(f"generated files out of date: {len(stale)}" + (" - run update" if stale else ""))
    return 0


def report_overrides(target, old_version):
    local = target / ".ba" / "local"
    if not local.is_dir():
        return
    for path in sorted(p for p in local.rglob("*") if p.is_file() and p.name != "README.md"):
        rel = path.relative_to(local)
        if (PACKAGE / "core" / rel).is_file():
            say("override", f".ba/local/{rel.as_posix()} overrides core - compare with the new .ba/core/{rel.as_posix()}")


def changelog_since(installed):
    log = PACKAGE / "CHANGELOG.md"
    if not log.is_file():
        return []
    sections = re.split(r"^(## .*)$", log.read_text(encoding="utf-8"), flags=re.M)
    out = []
    for i in range(1, len(sections), 2):
        version = re.match(r"## (\d+\.\d+\.\d+)", sections[i])
        if version and vtuple(version.group(1)) > vtuple(installed):
            out.append((sections[i], sections[i + 1].strip()))
    return out


def parse_tools(text):
    if not text:
        return None
    tools = list(adapters.TOOLS) if text == "all" else [t for t in re.split(r"\s*,\s*", text) if t]
    unknown = [t for t in tools if t not in adapters.TOOLS]
    if unknown:
        raise SystemExit(f"unknown tools: {', '.join(unknown)} (choose from {', '.join(adapters.TOOLS)} or all)")
    return tools


def main(argv=None):
    parser = argparse.ArgumentParser(prog="install", description=f"Install BA Pipeline {VERSION} into a project")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("init", "update", "status"):
        p = sub.add_parser(name)
        p.add_argument("--target", required=True, help="project root")
        if name != "status":
            p.add_argument("--tools", help=f"comma-separated: {', '.join(adapters.TOOLS)} or all")
            p.add_argument("--dry-run", action="store_true")
            p.add_argument("--model", help="the AI model your team uses, recorded on every audit event "
                                          "(.ba/config.json -> model)")
        if name == "init":
            p.add_argument("--requirements-dir", default="requirements")
            p.add_argument("--from-legacy", action="store_true", help="migrate the original pre-package layout")
        if name == "update":
            p.add_argument("--force", action="store_true", help="allow installing an older version")
    args = parser.parse_args(argv)
    target = Path(args.target).resolve()
    if not target.is_dir():
        print(f"no such folder: {target}")
        return 1
    return {"init": cmd_init, "update": cmd_update, "status": cmd_status}[args.command](target, args)


if __name__ == "__main__":
    sys.exit(main())
