#!/usr/bin/env python3
"""Install, update and inspect BA Pipeline in a project (Python 3.9+, standard library only).

  python install.py init   --target <project> [--tools claude,agents-md] [--requirements-dir requirements] [--from-legacy]
  python install.py update --target <project> [--tools ...] [--force] [--dry-run]
  python install.py status --target <project>

What goes where in the project:
  .ba/core/      the workflow (manual, stages, reviewer, templates, checklists, profiles) - replaced on update
  .ba/tools/     ba.py and adapters.py                                                     - replaced on update
  .ba/VERSION    the installed version
  .ba/config.json  project settings: ba_version (the pin), requirements_dir, tools        - kept on update
  .ba/local/     the project's own profiles, templates, checklists, glossary (override core) - never touched
  + the per-tool files generated by tools/adapters.py (see adapters/CAPABILITIES.md)

`update` refuses to install an older version than the pin unless --force, applies template migrations to every
feature's _status.md (recorded in the audit trail), regenerates the adapters and shows the changelog since the
installed version. `--from-legacy` moves the original Claude-only layout (CLAUDE.md with the full manual,
.claude/skills/ba-*, .claude/hooks/*.ps1, root templates/ checklists/ profiles/) into .ba/backup/ first.
"""

import argparse
import datetime
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parent
sys.path.insert(0, str(PACKAGE / "tools"))
import adapters  # noqa: E402

VERSION = (PACKAGE / "VERSION").read_text(encoding="utf-8").strip()
DEFAULT_TOOLS = ["claude", "agents-md"]
LOCAL_DIRS = ("profiles", "templates", "checklists")

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def vtuple(text):
    return tuple(int(x) for x in re.findall(r"\d+", text)[:3]) or (0,)


PRODUCT = "BA Pipeline"


def product(config):
    """Name of the installed product. Predecessors: BA Copilot (0.x), then BA Guardian Angel (1.x, no product key)."""
    if config.get("product"):
        return config["product"]
    return "BA Copilot" if vtuple(config.get("ba_version") or "0") < (1, 0, 0) else "BA Guardian Angel"


def say(state, text):
    print(f"{state:12} {text}")


# --------------------------------------------------------------------------- config

def config_path(target):
    return target / ".ba" / "config.json"


def read_config(target):
    path = config_path(target)
    return json.loads(path.read_text(encoding="utf-8-sig")) if path.is_file() else None


def write_config(target, config, dry_run):
    if not dry_run:
        config_path(target).parent.mkdir(parents=True, exist_ok=True)
        adapters.write_lf(config_path(target), json.dumps(config, indent=2) + "\n")


# --------------------------------------------------------------------------- package copy

def copy_package(target, dry_run):
    ba = target / ".ba"
    for name in ("core", "tools"):
        dest = ba / name
        say("replace" if dest.exists() else "create", f".ba/{name}/")
        if not dry_run:
            if dest.exists():
                shutil.rmtree(dest)
            shutil.copytree(PACKAGE / name, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "build_power.py"))
    say("write", f".ba/VERSION ({VERSION})")
    if not dry_run:
        (ba / "VERSION").write_text(VERSION + "\n", encoding="utf-8")


LOCAL_README = """# Project overrides

Files here override the same path in `.ba/core/` (MANUAL §0). `.ba/core/` is replaced on every update; this
folder is never touched. Typical uses:

- `profiles/<name>.md` — your own approach profiles (`/ba-profile new` writes them here)
- `templates/<file>` — a template in your house style (copy from `.ba/core/templates/` first)
- `checklists/<file>` — a stricter or looser quality bar
- `glossary.md` — your organisation's glossary

After an update, compare overridden files with the new core version (`python .ba/tools/ba.py` doesn't do this
for you yet): `install.py status` lists overrides whose core file changed.
"""


def ensure_local(target, dry_run):
    local = target / ".ba" / "local"
    for name in LOCAL_DIRS:
        if not (local / name).is_dir():
            say("create", f".ba/local/{name}/")
            if not dry_run:
                (local / name).mkdir(parents=True, exist_ok=True)
    if not (local / "README.md").is_file():
        say("create", ".ba/local/README.md")
        if not dry_run:
            (local / "README.md").write_text(LOCAL_README, encoding="utf-8")
    ignore = target / ".ba" / ".gitignore"
    if not ignore.is_file() and not dry_run:
        ignore.write_text("tmp/\n", encoding="utf-8")


# --------------------------------------------------------------------------- template migrations (_status.md)

def _table_end(lines, start):
    i = start
    while i < len(lines) and lines[i].lstrip().startswith("|"):
        i += 1
    return i


def mig_preferences(text):
    if re.search(r"^## Preferences", text, re.M):
        return text
    block = ("## Preferences\n| Setting | Value |\n|---------|-------|\n| Stage prompts | on-deviation |\n"
             "| Elicitation round | 0 |\n\n")
    if re.search(r"^## Gates", text, re.M):
        return re.sub(r"^## Gates", lambda m: block + m.group(0), text, count=1, flags=re.M)
    return text.rstrip() + "\n\n" + block


def mig_elicitation_round(text):
    if re.search(r"^\|\s*Elicitation round\s*\|", text, re.M):
        return text
    lines = text.split("\n")
    head = next((i for i, l in enumerate(lines) if l.startswith("## Preferences")), None)
    if head is None:
        return text
    first = next((i for i in range(head + 1, len(lines)) if lines[i].lstrip().startswith("|")), None)
    if first is None:
        return text
    lines.insert(_table_end(lines, first), "| Elicitation round | 0 |")
    return "\n".join(lines)


def mig_revisit_at(text):
    lines = text.split("\n")
    head = next((i for i, l in enumerate(lines) if l.startswith("## Decision log")), None)
    if head is None:
        return text
    first = next((i for i in range(head + 1, len(lines)) if lines[i].lstrip().startswith("|")), None)
    if first is None or "Revisit at" in lines[first]:
        return text
    end = _table_end(lines, first)
    for i in range(first, end):
        row = lines[i].rstrip()
        if i == first:
            lines[i] = row + " Revisit at |"
        elif i == first + 1:
            lines[i] = row + "-----------|"
        else:
            lines[i] = row + " — |"
    return "\n".join(lines)


def mig_answer_mode(text):
    if re.search(r"^\|\s*Answer mode\s*\|", text, re.M):
        return text
    lines = text.split("\n")
    row = next((i for i, l in enumerate(lines) if re.match(r"^\|\s*Elicitation round\s*\|", l)), None)
    if row is None:
        return text
    lines.insert(row + 1, "| Answer mode | ask |")
    return "\n".join(lines)


def mig_questions_per_message(text):
    if re.search(r"^\|\s*Questions per message\s*\|", text, re.M):
        return text
    lines = text.split("\n")
    row = next((i for i, l in enumerate(lines) if re.match(r"^\|\s*Answer mode\s*\|", l)), None)
    if row is None:
        return text
    lines.insert(row + 1, "| Questions per message | 5 |")
    return "\n".join(lines)


GOVERNANCE_BLOCK = """## Governance
Who decides. Added by the {version} migration - fill it in: `ba check` *governance* FAILs from Scope on if the business
owner or the PO is not named.
| Role | Who (STK-) | Decides on | Source |
|------|-----------|------------|--------|
| Business owner (final say in conflicts) | | Priorities and conflicts between stakeholders; funds the work | |
| Product Owner | {po} | Scope, story priority, acceptance | {po_source} |
| Area owner: <area> | | Rules and data of <area> | |
| Gate approvers | | Scope (3), Review (8), Handoff (9) | |
| Escalation path | | <area owner> → PO → business owner | |
| Role conflicts | | e.g. BA is also PO: name who reviews the BA's decisions, or accept it (`D-`) | |

"""


def mig_governance(text):
    if re.search(r"^## Governance", text, re.M):
        return text
    m = re.search(r"^\|\s*Product Owner\s*\|\s*([^|]*?)\s*\|", text, re.M)
    po = m.group(1) if m else ""
    block = GOVERNANCE_BLOCK.format(version=VERSION, po=po, po_source="_status.md Product Owner field" if po else "")
    if re.search(r"^## Decision log", text, re.M):
        return re.sub(r"^## Decision log", lambda x: block + x.group(0), text, count=1, flags=re.M)
    return text.rstrip() + "\n\n" + block


def _add_preference(text, name, value, after):
    """Insert '| name | value |' into Preferences after the row 'after' (or at the end of the table)."""
    if re.search(r"^\|\s*" + re.escape(name) + r"\s*\|", text, re.M):
        return text
    lines = text.split("\n")
    head = next((i for i, l in enumerate(lines) if l.startswith("## Preferences")), None)
    if head is None:
        return text
    first = next((i for i in range(head + 1, len(lines)) if lines[i].lstrip().startswith("|")), None)
    if first is None:
        return text
    end = _table_end(lines, first)
    row = next((i for i in range(first, end) if re.match(r"^\|\s*" + re.escape(after) + r"\s*\|", lines[i])), end - 1)
    lines.insert(row + 1, f"| {name} | {value} |")
    return "\n".join(lines)


def mig_mode(text):
    return _add_preference(text, "Mode", "standard", "Stage prompts")


def mig_language(text):
    return _add_preference(text, "Language", "en", "Mode")


DELIVERY_GATES = [
    "| 10 Refine | Every story in the sprint meets the Definition of Ready (team + PO confirmed) | – | | |",
    "| 11 Test/UAT | RTM: every AC has a test with a real result and evidence; acceptance decision by the approver | – | | |",
    "| 12 Release | Scope reconciled with the RTM; known issues owned; handover accepted | – | | |",
]


def mig_delivery_gates(text):
    if re.search(r"^\|\s*10 Refine\s*\|", text, re.M):
        return text
    lines = text.split("\n")
    head = next((i for i, l in enumerate(lines) if l.startswith("## Gates")), None)
    if head is None:
        return text
    first = next((i for i in range(head + 1, len(lines)) if lines[i].lstrip().startswith("|")), None)
    if first is None:
        return text
    end = _table_end(lines, first)
    lines[end:end] = DELIVERY_GATES
    return "\n".join(lines)


