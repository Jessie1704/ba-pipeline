"""Tests for the rename to BA Pipeline: projects on BA Guardian Angel 1.x upgrade in place.
Run from the package root:  python -m unittest discover -s tests -v
"""

import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_install import InstallCase  # noqa: E402


class FromGuardianAngel(InstallCase):
    def make_guardian_project(self):
        """A project as BA Guardian Angel 1.2.1 left it: no product key, its own Kiro/Cursor files and block."""
        self.assertEqual(self.inst("init", "--tools", "kiro,cursor,agents-md")[0], 0)
        config = json.loads((self.tmp / ".ba/config.json").read_text(encoding="utf-8"))
        config.pop("product")
        config["ba_version"] = "1.2.1"
        (self.tmp / ".ba/config.json").write_text(json.dumps(config), encoding="utf-8")
        for new, old in ((".kiro/steering/ba-pipeline.md", ".kiro/steering/ba-guardian.md"),
                         (".cursor/rules/ba-pipeline.mdc", ".cursor/rules/ba-guardian.mdc")):
            text = (self.tmp / new).read_text(encoding="utf-8").replace("generated by BA Pipeline",
                                                                       "generated by BA Guardian Angel")
            (self.tmp / old).write_text(text, encoding="utf-8")
            (self.tmp / new).unlink()
        agents = self.tmp / "AGENTS.md"
        agents.write_text(agents.read_text(encoding="utf-8").replace("BA-PIPELINE:", "BA-GUARDIAN:"), encoding="utf-8")

    def test_update_from_guardian_angel_needs_no_force(self):
        self.make_guardian_project()
        code, out = self.inst("update")
        self.assertEqual(code, 0, out)
        self.assertIn("Updating BA Guardian Angel 1.2.1 -> BA Pipeline 1.0.0", out)
        self.assertIn("## 1.0.0", out)
        config = json.loads((self.tmp / ".ba/config.json").read_text(encoding="utf-8"))
        self.assertEqual((config["product"], config["ba_version"]), ("BA Pipeline", "1.0.0"))

    def test_old_files_and_block_are_replaced(self):
        self.make_guardian_project()
        self.assertEqual(self.inst("update")[0], 0)
        self.assertFalse((self.tmp / ".kiro/steering/ba-guardian.md").exists())
        self.assertFalse((self.tmp / ".cursor/rules/ba-guardian.mdc").exists())
        self.assertTrue((self.tmp / ".kiro/steering/ba-pipeline.md").is_file())
        self.assertTrue((self.tmp / ".cursor/rules/ba-pipeline.mdc").is_file())
        agents = (self.tmp / "AGENTS.md").read_text(encoding="utf-8")
        self.assertEqual(agents.count("BA-PIPELINE:START"), 1)
        self.assertNotIn("BA-GUARDIAN", agents)

    def test_status_offers_the_update(self):
        self.make_guardian_project()
        code, out = self.inst("status")
        self.assertIn("BA Guardian Angel 1.2.1 installed", out)
        self.assertIn("update available", out)

    def test_downgrade_within_ba_pipeline_is_still_refused(self):
        self.assertEqual(self.inst("init")[0], 0)
        config = json.loads((self.tmp / ".ba/config.json").read_text(encoding="utf-8"))
        config["ba_version"] = "1.2.1"
        (self.tmp / ".ba/config.json").write_text(json.dumps(config), encoding="utf-8")
        code, out = self.inst("update")
        self.assertEqual(code, 1)
        self.assertIn("Refusing to downgrade", out)


if __name__ == "__main__":
    unittest.main()
