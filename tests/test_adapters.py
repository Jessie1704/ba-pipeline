"""Tests for tools/adapters.py. Run from the package root:  python -m unittest discover -s tests -v"""

import io
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PACKAGE / "tools"))
import adapters  # noqa: E402

STAGES = [name for name, _ in adapters.stages()]


class AdapterCase(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="ba-adapt-"))

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def generate(self, tools="all", dry_run=False):
        tool_list = list(adapters.TOOLS) if tools == "all" else tools.split(",")
        return adapters.generate(self.tmp, tool_list, dry_run)

    def read(self, rel):
        return (self.tmp / rel).read_text(encoding="utf-8")


class GenerateTests(AdapterCase):
    def test_every_stage_has_a_command_in_every_tool(self):
        self.assertEqual(len(STAGES), 20)
        self.generate()
        for name in STAGES:
            for rel in (f".claude/skills/{name}/SKILL.md", f".github/prompts/{name}.prompt.md",
                        f".cursor/commands/{name}.md", f".gemini/commands/{name}.toml", f".kiro/steering/{name}.md"):
                text = self.read(rel)
                self.assertIn(f".ba/core/stages/{name}.md", text, rel)
                self.assertIn("generated by BA Pipeline", text, rel)

    def test_instruction_files_point_at_manual_and_list_stages(self):
        self.generate()
        for rel in ("CLAUDE.md", "AGENTS.md", ".github/copilot-instructions.md", "GEMINI.md", ".cursor/rules/ba-pipeline.mdc",
                    ".kiro/steering/ba-pipeline.md"):
            text = self.read(rel)
            self.assertIn(".ba/core/MANUAL.md", text, rel)
            for name in STAGES:
                self.assertIn(f"`{name}`", text, f"{name} missing from {rel}")

    def test_second_run_changes_nothing(self):
        self.generate()
        states = {state for state, _ in self.generate()}
        self.assertEqual(states, {"unchanged"})

    def test_dry_run_writes_nothing(self):
        actions = self.generate(dry_run=True)
        self.assertTrue(actions)
        self.assertEqual(list(self.tmp.iterdir()), [])

    def test_user_content_is_kept(self):
        (self.tmp / "AGENTS.md").write_text("# Team notes\n\nKeep me.\n", encoding="utf-8")
        (self.tmp / ".cursor" / "commands").mkdir(parents=True)
        (self.tmp / ".cursor" / "commands" / "ba-next.md").write_text("my own command\n", encoding="utf-8")
        actions = dict((rel, state) for state, rel in self.generate())
        self.assertTrue(self.read("AGENTS.md").startswith("# Team notes\n\nKeep me.\n"))
        self.assertIn(adapters.BLOCK_START, self.read("AGENTS.md"))
        self.assertEqual(self.read(".cursor/commands/ba-next.md"), "my own command\n")
        self.assertEqual(actions[".cursor/commands/ba-next.md"], "skipped (user file)")

    def test_managed_block_is_replaced_not_duplicated(self):
        self.generate("agents-md")
        text = self.read("AGENTS.md").replace("act as the BA Pipeline assistant", "OLD TEXT")
        (self.tmp / "AGENTS.md").write_text(text + "\n## Added by user later\n", encoding="utf-8")
        self.generate("agents-md")
        text = self.read("AGENTS.md")
        self.assertEqual(text.count(adapters.BLOCK_START), 1)
        self.assertNotIn("OLD TEXT", text)
        self.assertIn("## Added by user later", text)

    def test_settings_merged_once(self):
        settings = self.tmp / ".claude" / "settings.json"
        settings.parent.mkdir()
        settings.write_text(json.dumps({"model": "opus", "permissions": {"allow": ["Bash(git *)"]}}), encoding="utf-8")
        self.generate("claude")
        self.generate("claude")
        data = json.loads(settings.read_text(encoding="utf-8"))
        self.assertEqual(data["model"], "opus")
        self.assertEqual(data["permissions"]["allow"], ["Bash(git *)"])
        self.assertIn("Edit(requirements/**/_audit/*.jsonl)", data["permissions"]["deny"])
        hooks = [h for g in data["hooks"]["PostToolUse"] for h in g["hooks"]]
        self.assertEqual(len(hooks), 1)
        self.assertIn("audit hook", hooks[0]["command"])

    def test_gemini_commands_are_valid_toml(self):
        try:
            import tomllib  # Python 3.11+
        except ImportError:
            self.skipTest("tomllib needs Python 3.11+")
        self.generate("gemini")
        for name in STAGES:
            data = tomllib.loads(self.read(f".gemini/commands/{name}.toml"))
            self.assertIn("{{args}}", data["prompt"])
            self.assertTrue(data["description"])

    def test_frontmatter_is_first(self):
        self.generate()
        for rel in ([f".claude/skills/{n}/SKILL.md" for n in STAGES] + [f".kiro/steering/{n}.md" for n in STAGES]
                    + [".claude/agents/requirements-reviewer.md", ".cursor/rules/ba-pipeline.mdc", ".kiro/steering/ba-pipeline.md"]):
            self.assertTrue(self.read(rel).startswith("---\n"), rel)


@unittest.skipUnless(shutil.which("bash"), "needs bash to run the Claude hook command")
class HookCommandTest(AdapterCase):
    def test_generated_hook_records_an_edit(self):
        self.generate("claude")
        shutil.copytree(PACKAGE / "core", self.tmp / ".ba" / "core")
        shutil.copytree(PACKAGE / "tools", self.tmp / ".ba" / "tools")
        shutil.copytree(PACKAGE / "examples" / "requirements", self.tmp / "requirements")
        log = self.tmp / "requirements" / "expense-claims" / "_audit" / "events.jsonl"
        before = len(log.read_text(encoding="utf-8").splitlines())
        command = json.loads(self.read(".claude/settings.json"))["hooks"]["PostToolUse"][0]["hooks"][0]["command"]
        payload = json.dumps({"session_id": "t", "tool_name": "Edit",
                              "tool_input": {"file_path": str(self.tmp / "requirements" / "expense-claims" / "03-scope.md")}})
        env = dict(__import__("os").environ, CLAUDE_PROJECT_DIR=str(self.tmp))
        result = subprocess.run(["bash", "-c", command], input=payload.encode(), env=env, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        lines = log.read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(lines), before + 1)
        self.assertIn('"source":"hook"', lines[-1])


class KiroTest(AdapterCase):
    def test_steering_inclusion_modes_and_file_references(self):
        self.generate("kiro")
        main = self.read(".kiro/steering/ba-pipeline.md")
        self.assertIn("inclusion: always", main)
        self.assertIn("#[[file:.ba/core/MANUAL.md]]", main)
        for name in STAGES:
            text = self.read(f".kiro/steering/{name}.md")
            self.assertIn("inclusion: manual", text)
            self.assertIn(f"#[[file:.ba/core/stages/{name}.md]]", text)


